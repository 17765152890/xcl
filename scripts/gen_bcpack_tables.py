#!/usr/bin/env python3
"""Writes crates/xcl/src/hle/bcpack/tables.rs from the BCPack table file.

    python scripts/gen_bcpack_tables.py <bcpack-tables.bin> [out.rs]

The file holds the format's constants (model frequencies, rank tables, BC7 control words,
dictionaries); `Tables::parse` in `mod.rs` documents its layout. It is kept as Rust source because
the repository takes no binary files outside tests/data/.
"""
import sys
from pathlib import Path

src = Path(sys.argv[1]).read_bytes()
out = Path(sys.argv[2] if len(sys.argv) > 2 else "crates/xcl/src/hle/bcpack/tables.rs")
lines = [
    "// Generated by scripts/gen_bcpack_tables.py from the BCPack table file; do not edit.",
    "// Layout: see `Tables::parse` in mod.rs.",
    "",
    f"pub static TABLES: [u8; {len(src)}] = [",
]
for i in range(0, len(src), 24):
    lines.append("    " + ", ".join(f"0x{b:02x}" for b in src[i:i + 24]) + ",")
lines.append("];")
