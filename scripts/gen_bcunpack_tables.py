#!/usr/bin/env python3
"""Generate crates/xcl/src/hle/bcunpack/tables.rs from the BCPack tables JSON.

Input: `formats/data/bcpack-tables.json` of the SixNG format notes
(https://github.com/TrinitronClient/GTA6-Asset-Info). Its values come from MIT-licensed
work: the static rANS models from Microsoft's silicon-rans, the BC1 preset slots and the
selector quadrant codebook from bcpack-rs (see THIRD_PARTY.md).

    python scripts/gen_bcunpack_tables.py <bcpack-tables.json> > crates/xcl/src/hle/bcunpack/tables.rs
"""
import json
import sys


def main() -> None:
    data = json.load(open(sys.argv[1], encoding="utf-8"))
    models = data["rans_models"]["models"]
    assert len(models) == 144
    out = []
    w = out.append
    w("// Generated by scripts/gen_bcunpack_tables.py from the SixNG notes' bcpack-tables.json – do not edit.")
    w("// Values: static rANS models from Microsoft's silicon-rans (MIT); BC1 preset slots and selector")
    w("// quadrant codebook from bcpack-rs (MIT). See THIRD_PARTY.md.")
    w("")
    w("/// Static rANS models, `eab * 16 + q`: (base, freq) of segment k (symbol 0, then [2^(k-1), 2^k)),")
    w("/// `eab + 2` segments; the rest are unused.")
    w("pub const MODELS: [[(u32, u32); 10]; 144] = [")
    for i, m in enumerate(models):
        eab, q = m["eab"], m["q"]
        assert i == eab * 16 + q, (i, eab, q)
        segs = m["segments"]
        assert len(segs) == eab + 2
        for k, s in enumerate(segs):
            first = 0 if k == 0 else 1 << (k - 1)
            count = 1 if k == 0 else 1 << (k - 1)
            assert s["first_symbol"] == first and s["symbols"] == count, (i, k, s)
        pairs = [(s["base"], s["freq"]) for s in segs] + [(0, 0)] * (10 - len(segs))
        w("    [" + ", ".join(f"({b}, {f})" for b, f in pairs) + f"], // eab {eab} q {q}")
    w("];")
    w("")
    presets = data["bc1"]["presets"]["slots"]
    assert len(presets) == 256
    w("/// BC1 history (preset) slots: [R0, G0, B0, R1, G1, B1] (5, 6, 5, 5, 6, 5 bits); None = never referenced.")
    w("pub const BC1_PRESETS: [Option<[u8; 6]>; 256] = [")
    for i, p in enumerate(presets):
        w("    None," if p is None else "    Some([" + ", ".join(str(v) for v in p) + "]),")
    w("];")
    w("")
    book = data["bc1"]["selector_codebook"]["entries"]
    assert len(book) == 256 and all(len(e) == 4 for e in book)
    assert sorted(tuple(e) for e in book) == sorted({tuple(e) for e in book}), "codebook not a bijection"
    w("/// BC1 selector quadrant codebook: symbol -> 2-bit codes of a 2x2 pixel group (TL, TR, BL, BR).")
    w("pub const BC1_CODEBOOK: [[u8; 4]; 256] = [")
    for e in book:
        w("    [" + ", ".join(str(v) for v in e) + "],")
    w("];")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
